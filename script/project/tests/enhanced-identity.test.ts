import assert from "node:assert/strict";
import { memory } from "./state-storage-mock";
import { loadEnhancementIdentity } from "../services/enhanced-account";
let generated = 0;
Object.assign(globalThis, { UUID: { string() { generated++; return "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee"; } } });
Object.assign(Crypto, { generateSymmetricKey() { return { toHexString: () => "0123456789abcdef0123456789abcdef" }; } });
const initial = loadEnhancementIdentity();
assert.equal(initial.accountId, "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee");
assert.equal(initial.androidId, "0123456789abcdef");
assert.deepEqual(loadEnhancementIdentity(), initial);
assert.equal(generated, 1, "relaunch and widget consumers keep the same installation identity");
const files = [...memory.keys()].filter(key => key.includes("account-enhancement-identity-v1.json"));
assert.ok(files.length);
memory.delete("pipi_deliveries_account_enhancement_identity_shared_v1");
memory.delete("keychain:pipi_deliveries_account_enhancement_identity_v1");
for (const key of files) memory.set(key, "invalid identity record");
assert.throws(() => loadEnhancementIdentity(), /身份读取失败/);
assert.equal(generated, 1, "corruption cannot silently rotate an upstream binding identity");
memory.clear();
const read = FileManager.existsSync;
FileManager.existsSync = () => { throw new Error("synthetic inaccessible store"); };
assert.throws(() => loadEnhancementIdentity());
FileManager.existsSync = read;
assert.equal(generated, 1);
console.log("Enhanced installation identity durability and unreadable-store tests passed");
